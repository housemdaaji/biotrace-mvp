/** Metric icon key for MagoScoreCard / map / survey */
export type MetricIconKey = 'deforestation' | 'agroecology' | 'biodiversity' | 'carbon' | 'water';

export function MetricIcon({ iconKey, className }: { iconKey: MetricIconKey; className?: string }) {
  const c = cn('w-5 h-5 inline-block align-middle', className);
  switch (iconKey) {
    case 'deforestation':
      return <TreeIcon className={c} />;
    case 'agroecology':
      return <MedalIcon className={c} />;
    case 'biodiversity':
      return (
        <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" className={c} aria-hidden>
          <path d="M12 22c4-4 8-7 8-12a8 8 0 0 0-16 0c0 5 4 8 8 12z" />
        </svg>
      );
    case 'carbon':
      return <WindIcon className={c} />;
    case 'water':
      return <DropletIcon className={c} />;
    default:
      return <TreeIcon className={c} />;
  }
}
